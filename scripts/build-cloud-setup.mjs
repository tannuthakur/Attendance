// Bundles supabase/migrations + seed into paste-ready files for the Supabase SQL Editor.
// Usage: pnpm db:bundle   (output: supabase/cloud-setup/*.sql)
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';

const out = 'supabase/cloud-setup';
mkdirSync(out, { recursive: true });
const header = (title) => `-- ${title}\n-- GENERATED by scripts/build-cloud-setup.mjs — do not edit; edit supabase/migrations instead.\n`;

const migrations = readdirSync('supabase/migrations').filter((f) => f.endsWith('.sql')).sort();
writeFileSync(
  `${out}/01_schema.sql`,
  header('Step 1 — full database schema (tables, RLS, functions, views, storage buckets). Run ONCE on an empty project.') +
    migrations.map((f) => `\n-- ===== ${f} =====\n${readFileSync(`supabase/migrations/${f}`, 'utf8')}`).join(''),
);

// In Supabase Cloud pgcrypto lives in the `extensions` schema.
const seed = readFileSync('supabase/seed.sql', 'utf8')
  .replaceAll("crypt('", "extensions.crypt('")
  .replaceAll("gen_salt('bf')", "extensions.gen_salt('bf')");
writeFileSync(
  `${out}/03_demo_data_optional.sql`,
  header('Step 3 (OPTIONAL) — demo data: 15 employees, 4 projects, attendance, holidays, 3 invoices, plus demo users admin@example.com / viewer@example.com. Skip for production.') +
    seed,
);
console.log(`wrote ${out}/01_schema.sql and ${out}/03_demo_data_optional.sql`);
